"""Write the game's config modules (src/shared/Config/Content/*.luau) from the CSVs in content/.
Every number of the game lives in those CSVs (CLAUDE.md, "Tous les chiffres viennent de la config").

    py scripts/make_config.py           write the modules
    py scripts/make_config.py --check   exit 1 if a module differs from what the CSVs give
"""

import csv
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "content")
OUT = os.path.join(ROOT, "src", "shared", "Config", "Content")
HEADER = "--!strict\n-- GENERATED by scripts/make_config.py from content/{src}. Do not edit: change the CSV and rerun.\n"
NUMBER = re.compile(r"^-?\d+(\.\d+)?$")


def rows(name):
    with open(os.path.join(CONTENT, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def num(s):
    v = float(s)
    return int(v) if v.is_integer() and abs(v) < 2**53 else v


def value(s):
    """A constant: a number, a list of numbers (a;b;c) or a string (a hex colour)."""
    s = s.strip()
    if NUMBER.match(s):
        return num(s)
    if ";" in s and all(NUMBER.match(p) for p in s.split(";")):
        return [num(p) for p in s.split(";")]
    return s


def lua(v, indent=1):
    """A Python value as a Luau literal."""
    pad = "\t" * indent
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        r = repr(v)
        return r if ("e" in r or "." in r or "inf" in r) else r + ".0"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "{}"
        if all(isinstance(x, (int, float)) for x in v):
            return "{ " + ", ".join(lua(x) for x in v) + " }"
        inner = ",\n".join(pad + lua(x, indent + 1) for x in v)
        return "{\n" + inner + ",\n" + "\t" * (indent - 1) + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        parts = []
        for k, x in v.items():
            key = k if k.isidentifier() else "[" + json.dumps(k) + "]"
            parts.append(pad + key + " = " + lua(x, indent + 1))
        return "{\n" + ",\n".join(parts) + ",\n" + "\t" * (indent - 1) + "}"
    raise TypeError(type(v))


def flag(s):
    if s not in ("0", "1"):
        raise ValueError(f"expected 0 or 1, got {s!r}")
    return s == "1"


def build():
    mods = {}

    constants = {}
    for r in rows("constants.csv"):
        if r["key"] in constants:
            raise ValueError(f"constants.csv: {r['key']} twice")
        constants[r["key"]] = value(r["value"])
    mods["Constants"] = ("constants.csv", constants)

    mods["Nights"] = ("nights.csv", [
        {"night": int(r["night"]), "length": num(r["length"]), "flicker": flag(r["flicker"]),
         "blackout": flag(r["blackout"]), "liveStart": num(r["live_start"]), "liveEnd": num(r["live_end"]),
         "flickerStart": num(r["flicker_start"]), "flickerEnd": num(r["flicker_end"]),
         "blackoutStart": num(r["blackout_start"]), "blackoutEnd": num(r["blackout_end"]),
         "falseAlarmEvery": num(r["false_alarm_every"]), "holdoutsMin": int(r["holdouts_min"]),
         "holdoutsMax": int(r["holdouts_max"]), "name": r["name"], "unseenSpeed": num(r["unseen_speed"]),
         "extraScans": int(r["extra_scans"]), "cables": int(r["cables"]), "intro": r["intro"]}
        for r in rows("nights.csv")])

    mods["Cameras"] = ("cameras.csv", [
        {"id": r["id"], "zone": r["zone"], "x": num(r["x"]), "y": num(r["y"]), "z": num(r["z"]),
         "tx": num(r["tx"]), "ty": num(r["ty"]), "tz": num(r["tz"]), "hfov": num(r["hfov"]),
         "vfov": num(r["vfov"]), "range": num(r["range"]), "always": flag(r["always"])}
        for r in rows("cameras.csv")])

    def blocks(name):
        out = []
        for r in rows(name):
            count = int(r["count"])
            for i in range(count):
                out.append({
                    "id": r["id"] if count == 1 else f"{r['id']}{i + 1}", "kind": r["kind"],
                    "x": num(r["x"]) + i * num(r["step_x"]), "y": num(r["y"]), "z": num(r["z"]),
                    "sx": num(r["sx"]), "sy": num(r["sy"]), "sz": num(r["sz"]),
                    "occludes": flag(r["occludes"]), "blocks": flag(r["blocks"])})
        return out

    mods["Map"] = ("map_p3.csv", blocks("map_p3.csv"))
    mods["LobbyMap"] = ("map_lobby.csv", blocks("map_lobby.csv"))

    mods["Lifts"] = ("lifts.csv", [
        {"id": r["id"], "label": r["label"], "x": num(r["x"]), "y": num(r["y"]), "z": num(r["z"])}
        for r in rows("lifts.csv")])

    mods["LobbyProps"] = ("lobby_props.csv", [
        {"id": r["id"], "model": r["model"], "x": num(r["x"]), "y": num(r["y"]), "z": num(r["z"]),
         "yaw": num(r["yaw"])}
        for r in rows("lobby_props.csv")])

    mods["Spots"] = ("spots.csv", [
        {"id": r["id"], "kind": r["kind"], "label": r["label"], "x": num(r["x"]), "y": num(r["y"]),
         "z": num(r["z"]), "yaw": num(r["yaw"])}
        for r in rows("spots.csv")])

    def ids(s):
        return [x for x in s.split(";") if x]

    mods["Tasks"] = ("tasks.csv", [
        {"id": r["id"], "kind": r["kind"], "label": r["label"], "item": r["item"], "pickup": ids(r["pickup"]),
         "target": ids(r["target"]), "effect": ids(r["effect"]), "pay": num(r["pay"]), "hold": num(r["hold"])}
        for r in rows("tasks.csv")])

    mods["Signs"] = ("signs.csv", [
        {"id": r["id"], "x": num(r["x"]), "y": num(r["y"]), "z": num(r["z"]), "yaw": num(r["yaw"]),
         "flat": flag(r["flat"]), "w": num(r["w"]), "h": num(r["h"]), "text": r["text"], "color": r["color"],
         "alpha": num(r["alpha"])}
        for r in rows("signs.csv")])

    mods["CarColors"] = ("car_colors.csv", [r["hex"] for r in rows("car_colors.csv")])

    mods["Tapes"] = ("tapes.csv", [
        {"id": r["id"], "title": r["title"], "stamp": r["stamp"], "lines": [x.strip() for x in r["lines"].split("|")]}
        for r in rows("tapes.csv")])

    mods["Radio"] = ("radio.csv", [
        {"id": r["id"], "night": int(r["night"]), "trigger": r["trigger"], "delay": num(r["delay"]), "text": r["text"]}
        for r in rows("radio.csv")])

    mods["Logbook"] = ("logbook.csv", [{"night": int(r["night"]), "line": r["line"]} for r in rows("logbook.csv")])

    mods["Items"] = ("items.csv", [{"id": r["id"], "name": r["name"]} for r in rows("items.csv")])

    mods["Shop"] = ("shop.csv", [
        {"id": r["id"], "name": r["name"], "kind": r["kind"], "price": num(r["price"]),
         "product": int(r["robux_product"]), "art": r["art"], "frame": r["frame"], "rec": r["rec"], "text": r["text"],
         "blurb": r["blurb"]}
        for r in rows("shop.csv")])

    mods["Daily"] = ("daily.csv", [
        {"day": int(r["day"]), "pay": num(r["pay"])} for r in rows("daily.csv")])

    mods["Codes"] = ("codes.csv", [
        {"code": r["code"].strip().upper(), "pay": num(r["pay"])} for r in rows("codes.csv")])

    out = {}
    for name, (src, data) in mods.items():
        out[name + ".luau"] = HEADER.format(src=src) + "return " + lua(data) + "\n"
    names = sorted(mods)
    init = HEADER.format(src="*.csv") + "return {\n"
    for n in names:
        init += f'\t{n} = require(if script then script:WaitForChild("{n}") else "@self/{n}"),\n'
    out["init.luau"] = init + "}\n"
    return out


def main():
    check = "--check" in sys.argv
    out = build()
    stale = []
    os.makedirs(OUT, exist_ok=True)
    existing = {f for f in os.listdir(OUT) if f.endswith(".luau")}
    for name, text in out.items():
        path = os.path.join(OUT, name)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                old = f.read()
        if old != text:
            stale.append(name)
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    extra = sorted(existing - set(out))
    if check:
        if stale or extra:
            print("config is stale, run: py scripts/make_config.py (" + ", ".join(stale + extra) + ")")
            sys.exit(1)
        print(f"config up to date ({len(out)} modules)")
        return
    for name in extra:
        os.remove(os.path.join(OUT, name))
    print(f"{len(out)} modules, {len(stale)} rewritten, {len(extra)} removed")


main()
